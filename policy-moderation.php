<article class="policy-content">
    <h1>Moderation Policy</h1>
    <p class="policy-date">Last Updated: October 19, 2026</p>

    <p>This website is for demonstration and academic purposes only as part of an SIA subject project. It is not a real barangay service or official reporting platform.</p>

    <p>This policy explains how incident reports and supporting evidence should be submitted and reviewed within the prototype.</p>

    <h2>1. Content That Is Not Allowed</h2>
    <p>Reports or evidence may be flagged for review if they contain:</p>
    <ul>
        <li>Threats, harassment, hate speech, or abusive language.</li>
        <li>Knowingly false accusations or malicious reports.</li>
        <li>Spam, repeated test submissions, or unrelated content.</li>
        <li>Instructions or material encouraging unlawful activity.</li>
        <li>Personal information about other people that is unnecessary to report the incident.</li>
        <li>Photos, videos, or other material submitted without appropriate permission.</li>
    </ul>

    <h2>2. How Reports Are Reviewed</h2>
    <p>Authorized staff or administrators may inspect submitted reports and update their status. A status change records the progress of a report in the system. A status such as “Verified” does not, by itself, establish a legal finding or prove that every allegation is true.</p>

    <h2>3. Reporting Inappropriate Content</h2>
    <p>If you notice inappropriate information in the prototype, contact the student project team or the instructor using the communication method provided for the project. Include the report number and explain the concern. Avoid reposting sensitive information in your complaint.</p>

    <h2>4. Removal Requests</h2>
    <p>The project team may remove test content or restrict access where practical and appropriate. Actual deletion may require a project administrator to remove the corresponding database record and uploaded files.</p>

    <h2>5. Repeat Misuse</h2>
    <p>Repeated submission of false, harmful, or unrelated content may result in restricted access to the demonstration system.</p>

    <h2>6. No Guarantee of Publication or Retention</h2>
    <p>The project team does not guarantee that every test report will remain available throughout development. Reports may be changed or removed during testing.</p>

    <h2>7. User Responsibility</h2>
    <p>Submit accurate information to the best of your knowledge. Avoid uploading unnecessary personal details or material that could endanger, embarrass, or identify another person.</p>

    <h2>8. Contact</h2>
    <p>For moderation or removal requests, email the student project team at <a href="mailto:barangaypitipiwpiw@gmail.com">barangaypitipiwpiw@gmail.com</a>, or use the communication method provided by your class or instructor.</p>
